"""Generate photo artwork, native four-gray data and honest B/W dither previews."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
EXAMPLE = Path(__file__).resolve().parents[1]
OUT = EXAMPLE / 'preview'
FONT = Path('/usr/share/fonts/truetype/dejavu')
def font(size, bold=True):
    return ImageFont.truetype(str(FONT / ('DejaVuSans-Bold.ttf' if bold else 'DejaVuSans.ttf')), size)
def render(variant, native=True):
    im = Image.new('L', (296, 128), 255)
    d = ImageDraw.Draw(im)
    # Draw text with a binary mask so the proposal has exactly four levels.
    def text(x, y, value, size, fill=0, bold=True, extra_weight=False, letter_spacing=0):
        mask = Image.new('1', im.size, 0)
        md = ImageDraw.Draw(mask)
        face = font(size, bold)
        if letter_spacing:
            # Keep a common baseline while reserving space for thicker strokes.
            cursor = x
            baseline_y = y - face.getbbox(value, anchor='la')[1]
            for char in value:
                for offset in range(2 if extra_weight else 1):
                    md.text((round(cursor) + offset, baseline_y), char,
                            font=face, fill=1, anchor='la')
                cursor += face.getlength(char) + letter_spacing
        else:
            md.text((x, y), value, font=face, fill=1, anchor='lt')
            if extra_weight:
                # One extra horizontal pixel strengthens small mono glyphs
                # without closing their counters with an all-around stroke.
                md.text((x + 1, y), value, font=face, fill=1, anchor='lt')
        im.paste(fill, (0, 0), mask)
    title = '2.9inch e-Paper'
    size = 28
    width = d.textbbox((0, 0), title, font=font(size))[2]
    text((296-width)//2, 6, title, size)
    d.rectangle((6, 40, 289, 80), fill=0)
    text(12, 42, '296×128', 36, fill=255)
    text(207, 57, 'Pixels', 19, fill=255)
    text(8, 88, 'ESP32-S3 + LR1121', 15, extra_weight=True)
    text(8, 109, '4 GRAY' if native else 'DITHER', 13,
         extra_weight=True, letter_spacing=1)
    for i, level in enumerate((255,170,85,0)):
        x = 80 + i*37
        d.rectangle((x, 106, x+29, 123), fill=level, outline=0, width=1)
    inv = variant == 'HF'
    d.rectangle((249, 87, 289, 123), fill=0 if inv else 255, outline=0, width=2)
    w = d.textbbox((0, 0), variant, font=font(22))[2]
    text(269-w//2, 97, variant, 22, fill=255 if inv else 0)
    assert set(im.getdata()) == {0, 85, 170, 255}
    return im
def dither(image):
    # Three of nine white dots for dark gray; six of nine for light gray.
    rank = ((0, 7, 3), (6, 5, 2), (4, 1, 8))
    result = Image.new('1', image.size)
    for y in range(image.height):
        for x in range(image.width):
            level = image.getpixel((x, y)) // 85
            result.putpixel((x, y), int(rank[y % 3][x % 3] < level * 3))
    return result


def pack_gray4(image):
    # The established board rotation maps (x,y) to (y,295-x).
    panel = image.transpose(Image.Transpose.ROTATE_90)
    levels = [v // 85 for v in panel.getdata()]
    return bytes((levels[i] << 6) | (levels[i+1] << 4) |
                 (levels[i+2] << 2) | levels[i+3]
                 for i in range(0, len(levels), 4))


def write_include(name, data):
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i+16]) + ','
            for i in range(0, len(data), 16)]
    (EXAMPLE / 'main' / name).write_text(
        '// Generated by tools/render_photo.py; do not edit by hand.\n'
        + '\n'.join(rows) + '\n')


def preview_sheet(images, native):
    sheet = Image.new('RGB', (984, 1000), '#eeeeeb')
    d = ImageDraw.Draw(sheet)
    title = '03 / FOUR-GRAY PHOTO DISPLAY' if native else '03 / B&W DITHER PHOTO DISPLAY'
    d.text((48, 26), title, font=font(22), fill='#25322b')
    for variant, y in [('HF',94),('LF',554)]:
        label = 'native gray target' if native else 'black/white dots'
        d.text((48,y-28), variant+'  /  296 x 128 px  /  '+label,
               font=font(16,False), fill='#56635c')
        sheet.paste(images[variant].convert('RGB').resize((888,384),
                    Image.Resampling.NEAREST),(48,y))
    return sheet


if __name__ == '__main__':
    OUT.mkdir(exist_ok=True)
    gray, bw = {}, {}
    for variant in ('HF', 'LF'):
        key = variant.lower()
        gray[variant] = render(variant)
        bw[variant] = dither(render(variant, native=False))
        gray[variant].save(OUT / f'photo_{key}_4gray.png')
        bw[variant].save(OUT / f'photo_{key}.png')
        write_include(f'photo_{key}_4gray.inc', pack_gray4(gray[variant]))
        write_include(f'photo_{key}.inc', bw[variant].tobytes())
    preview_sheet(gray, native=True).save(OUT / 'hf-lf-4gray-preview.png')
    preview_sheet(bw, native=False).save(OUT / 'hf-lf-preview.png')
